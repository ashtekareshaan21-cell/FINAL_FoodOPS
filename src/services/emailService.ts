const RESEND_API_KEY = process.env.RESEND_API_KEY;

export const emailService = {
  async sendEmail(to: string, subject: string, html: string) {
    if (!RESEND_API_KEY) {
      console.log(`[EMAIL MOCK] To: ${to} | Subject: ${subject}`);
      console.log(`[EMAIL MOCK] Body: ${html.replace(/<[^>]*>/g, '')}`);
      return { success: true, mock: true };
    }

    try {
      const response = await fetch('https://api.resend.com/emails', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${RESEND_API_KEY}`,
        },
        body: JSON.stringify({
          from: 'FoodOps Notification <notifications@foodops.org>',
          to,
          subject,
          html,
        }),
      });

      if (!response.ok) {
        const errData = await response.json();
        console.error('Resend email delivery failed:', errData);
        return { success: false, error: errData };
      }

      return { success: true };
    } catch (error) {
      console.error('Email dispatch error:', error);
      return { success: false, error };
    }
  },

  async sendNGOApprovedEmail(email: string, orgName: string) {
    return this.sendEmail(
      email,
      'FoodOps Partnership Approved 🎉',
      `<h1>Welcome to FoodOps, ${orgName}!</h1>
       <p>We are pleased to inform you that your FSSAI compliance documents have been reviewed and approved by our coordinator.</p>
       <p>You can now log in to the NGO Portal to claim nearby surplus food rescues and assign volunteer riders.</p>
       <br/>
       <p>Best regards,</p>
       <p>The FoodOps Team</p>`
    );
  },

  async sendDonationAcceptedEmail(email: string, title: string, ngoName: string) {
    return this.sendEmail(
      email,
      'Surplus Donation Claimed 📦',
      `<h1>Good news!</h1>
       <p>Your surplus food listing <strong>"${title}"</strong> has been accepted by <strong>${ngoName}</strong>.</p>
       <p>They are currently assigning a rider to pick up the items. You can track progress live from your Donor Dashboard.</p>
       <br/>
       <p>Best regards,</p>
       <p>The FoodOps Team</p>`
    );
  },

  async sendVolunteerAssignedEmail(email: string, title: string, volunteerName: string) {
    return this.sendEmail(
      email,
      'Rider Assigned to Surplus Collection 🚴',
      `<h1>Rescue Transit Started</h1>
       <p>A rider, <strong>${volunteerName}</strong>, has been dispatched by the NGO to collect your surplus listing <strong>"${title}"</strong>.</p>
       <p>Please prepare the food packages for collection.</p>
       <br/>
       <p>Best regards,</p>
       <p>The FoodOps Team</p>`
    );
  },

  async sendDonationCompletedEmail(email: string, title: string) {
    return this.sendEmail(
      email,
      'Food Rescue Successfully Completed! 🏁',
      `<h1>Thank you for your donation!</h1>
       <p>Your surplus listing <strong>"${title}"</strong> has been successfully delivered to the NGO base.</p>
       <p>Our database has logged the carbon and water footprint savings generated by this rescue. You can view your total cumulative impact metrics on your Donor Dashboard.</p>
       <br/>
       <p>Best regards,</p>
       <p>The FoodOps Team</p>`
    );
  },
};
